"""由 credits.json 生成 play/js/credits.js；加 --release 时再打一个发布 zip（index.html + play/ + 许可证）。

    python -m tools.build             # 只重新生成 credits.js
    python -m tools.build --release   # 另外生成 release/ai-business-blueprint-v<版本>.zip
"""
import json
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def credits():
    c = json.loads((ROOT / "credits.json").read_text(encoding="utf-8"))
    out = {
        "SERIES_NAME_ZH": c["SERIES_NAME"], "SERIES_NAME_EN": c["SERIES_NAME_EN"],
        "AUTHOR": c["AUTHOR"], "AUTHOR_EMAIL": c["AUTHOR_EMAIL"],
        "UNIVERSITY_EN": c["UNIVERSITY_EN"], "UNIVERSITY_KO": c["UNIVERSITY_KO"],
        "GH_USER": c["GH_USER"], "REPO_NAME": c["REPO_NAME"],
        "PAGES_URL": "https://%s.github.io/%s/" % (c["GH_USER"].lower(), c["REPO_NAME"]),
        "APP_NAME_ZH": c["APP_NAME_ZH"], "APP_NAME_EN": c["APP_NAME_EN"],
        "YEAR": c["YEAR"], "VERSION": c["VERSION"], "RELEASE_DATE": c["RELEASE_DATE"],
    }
    js = "/* Generated by tools/build.py from credits.json -- edit credits.json, then rebuild. */\nwindow.CREDITS = " + \
        json.dumps(out, ensure_ascii=False, indent=2) + ";\n"
    (ROOT / "play" / "js" / "credits.js").write_text(js, encoding="utf-8")
    return c


def release(c):
    out = ROOT / "release"
    out.mkdir(exist_ok=True)
    name = out / ("%s-v%s.zip" % (c["REPO_NAME"], c["VERSION"]))
    files = [ROOT / "index.html", ROOT / "LICENSE", ROOT / "LICENSE-docs", ROOT / "README.md"] + \
        sorted(p for p in (ROOT / "play").rglob("*") if p.is_file())
    with zipfile.ZipFile(name, "w", zipfile.ZIP_DEFLATED) as z:
        for f in files:
            z.write(f, f.relative_to(ROOT).as_posix())
    return name


if __name__ == "__main__":
    c = credits()
    print("已生成 play/js/credits.js")
    if "--release" in sys.argv:
        print("已生成", release(c).relative_to(ROOT))
